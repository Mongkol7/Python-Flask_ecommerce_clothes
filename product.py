def get_products_by_category():
    grouped_products = []
    category_lookup = {}

    for product in products:
        category = product["category"]

        if category not in category_lookup:
            category_group = {
                "name": category,
                "label": category.replace("-", " ").title(),
                "slug": category.lower().replace(" ", "-"),
                "products": [],
            }
            category_lookup[category] = category_group
            grouped_products.append(category_group)

        category_lookup[category]["products"].append(product)

    return grouped_products


def get_product_by_id(product_id):
    for product in products:
        if product["id"] == product_id:
            return product

    return None


def search_products(query):
    query = query.strip().lower()

    if not query:
        return products

    matched_products = []
    for product in products:
        if query in product["title"].lower():
            matched_products.append(product)

    return matched_products


def get_product_gender(product):
    gender_source = f"{product.get('image', '')} {product.get('title', '')}".lower()

    if "woman" in gender_source:
        return "woman"

    if "man" in gender_source:
        return "man"

    return None


def get_related_products(product_id):
    selected_product = get_product_by_id(product_id)

    if selected_product is None:
        return []

    selected_gender = get_product_gender(selected_product)
    related_products = []
    for product in products:
        same_category = product["category"] == selected_product["category"]
        same_gender = get_product_gender(product) == selected_gender
        different_product = product["id"] != selected_product["id"]

        if same_category and same_gender and different_product:
            related_products.append(product)

    return related_products


def get_cart_items(cart_cookie_data):
    cart_items = []

    for cart_item in cart_cookie_data:
        product = get_product_by_id(cart_item["id"])
        if product is None:
            continue

        item = product.copy()
        item["qty"] = cart_item["qty"]
        item["subtotal"] = item["price"] * item["qty"]
        cart_items.append(item)

    return cart_items
